    function applyI18n(lang) {
        const dict = I18N[lang] || I18N.en;
        // Plain text
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) el.textContent = dict[key];
        });
        // HTML content
        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            if (dict[key]) el.innerHTML = dict[key];
        });
        // Placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) el.placeholder = dict[key];
        });
        // Title (tooltip)
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (dict[key]) el.title = dict[key];
        });
        // Toggle active state
        document.querySelectorAll('.lang-item').forEach(b => {
            b.classList.toggle('active', b.dataset.lang === lang);
        });
        // Roda bahasa di kepala halaman dipusatkan saat halaman dimuat, sebelum
        // pilihan tersimpan sempat diterapkan. Tanpa pemusatan ulang, rodanya
        // berhenti di EN padahal isinya sudah bahasa lain.
        if (window.gmCenterLangWheel) window.gmCenterLangWheel();
        // Persist
        try { localStorage.setItem('docs_lang', lang); } catch (e) {}
        document.documentElement.lang = lang;
    }

